//! `cognoscenti procedural generate | replay | report`: the procedural track
//! (Plan 44 Phase 5) as three commands. See `docs/procedural-track.md` for
//! the run, its environment and what each prints.

use crate::adapter::{replay_stream, MemorySystem};
use crate::baselines::build_baseline;
use crate::manifest::{current_commit, sha256_file};
use crate::procedural::{generate_procedural, ProceduralConfig, ProceduralStream};
use crate::procedural_report::{rows_of, write_report, ProceduralRun, SCHEMA};
use crate::productions_http::ProductionsHttpSystem;
use crate::stream::Stream;
use crate::AchiralHttpSystem;
use anyhow::{bail, Context, Result};
use clap::{Parser, Subcommand};
use std::path::{Path, PathBuf};

pub const ARMS: [&str; 3] = ["declarative", "procedural", "bm25"];
const SEED_HEADER: &str = "# procedural-seed=";

#[derive(Parser, Debug)]
#[clap(name = "cognoscenti procedural")]
pub struct ProceduralArgs {
    #[clap(subcommand)]
    pub command: Command,
}

#[derive(Subcommand, Debug)]
pub enum Command {
    /// Write the track's stream for a seed (17 tuning; 4242 and 4243 report).
    Generate {
        #[clap(long)]
        seed: u64,
        #[clap(long)]
        out: PathBuf,
    },
    /// Replay a generated stream through one arm and save its run file.
    Replay {
        #[clap(long)]
        stream: PathBuf,
        /// declarative, procedural or bm25.
        #[clap(long)]
        arm: String,
        #[clap(long, default_value = "5")]
        replicates: usize,
        #[clap(long, default_value = "1")]
        top_k: usize,
        #[clap(long)]
        label: Option<String>,
        #[clap(long)]
        results_json: PathBuf,
    },
    /// Score run files against the registered decision rule and write HTML.
    Report {
        #[clap(long, num_args = 1.., required = true)]
        results: Vec<PathBuf>,
        /// Defaults to `report/` beside the first results file.
        #[clap(long)]
        out: Option<PathBuf>,
    },
}

pub fn run(args: &ProceduralArgs) -> Result<()> {
    match &args.command {
        Command::Generate { seed, out } => {
            let sha = generate(*seed, out)?;
            println!(
                "Generated {} (procedural track, seed {seed})",
                out.display()
            );
            println!("sha256 {sha}");
        }
        Command::Replay {
            stream,
            arm,
            replicates,
            top_k,
            label,
            results_json,
        } => {
            let run = replay(stream, arm, *replicates, *top_k, label.clone())?;
            println!("{}", summary_line(&run));
            run.save(results_json)?;
            println!("results saved to {}", results_json.display());
        }
        Command::Report { results, out } => {
            let runs = results
                .iter()
                .map(|p| ProceduralRun::load(p))
                .collect::<Result<Vec<_>>>()?;
            let out = out.clone().unwrap_or_else(|| {
                results[0]
                    .parent()
                    .unwrap_or_else(|| Path::new("."))
                    .join("report")
            });
            let index = write_report(&runs, &out)?;
            println!("report written to {}", index.display());
        }
    }
    Ok(())
}

fn jsonl(track: &ProceduralStream, seed: u64) -> String {
    let mut out = format!(
        "# Generated by cognoscenti procedural generate; no model in the loop.\n{SEED_HEADER}{seed}\n"
    );
    for item in &track.stream.items {
        out.push_str(&serde_json::to_string(item).expect("stream items serialise"));
        out.push('\n');
    }
    out
}

/// Writes the stream and returns its sha256.
pub fn generate(seed: u64, out: &Path) -> Result<String> {
    let track = generate_procedural(&ProceduralConfig::new(seed));
    std::fs::write(out, jsonl(&track, seed))
        .with_context(|| format!("writing {}", out.display()))?;
    sha256_file(&out.to_string_lossy())
}

/// Loads a generated stream and the spec it was made with. The spec is not
/// stored; it is regenerated from the seed in the header, and the file must
/// match what that seed generates, so a hand-edited stream is refused.
pub fn load_track(path: &Path) -> Result<(ProceduralStream, u64)> {
    let text =
        std::fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    let seed: u64 = text
        .lines()
        .find_map(|l| l.strip_prefix(SEED_HEADER))
        .context("not a procedural stream: no procedural-seed header (use `procedural generate`)")?
        .trim()
        .parse()
        .context("procedural-seed header is not a number")?;
    let track = generate_procedural(&ProceduralConfig::new(seed));
    if jsonl(&track, seed) != text {
        bail!(
            "{} does not match what seed {seed} generates; regenerate it with `procedural generate`",
            path.display()
        );
    }
    let loaded = Stream::from_jsonl(&text)?;
    debug_assert_eq!(loaded.items.len(), track.stream.items.len());
    Ok((track, seed))
}

fn build_arm(arm: &str, replicate: usize) -> Result<Box<dyn MemorySystem>> {
    match arm {
        "declarative" => Ok(Box::new(AchiralHttpSystem::from_env_at(replicate)?)),
        "procedural" => Ok(Box::new(ProductionsHttpSystem::from_env_at(replicate)?)),
        "bm25" => build_baseline("bm25", 30.0, 20),
        other => bail!("--arm must be one of {}, got {other}", ARMS.join(", ")),
    }
}

pub fn replay(
    stream_path: &Path,
    arm: &str,
    replicates: usize,
    top_k: usize,
    label: Option<String>,
) -> Result<ProceduralRun> {
    replay_with(stream_path, arm, replicates, top_k, label, build_arm)
}

/// `replay` with the system builder given, so a test can supply its own.
pub fn replay_with(
    stream_path: &Path,
    arm: &str,
    replicates: usize,
    top_k: usize,
    label: Option<String>,
    mut build: impl FnMut(&str, usize) -> Result<Box<dyn MemorySystem>>,
) -> Result<ProceduralRun> {
    if !ARMS.contains(&arm) {
        bail!("--arm must be one of {}, got {arm}", ARMS.join(", "));
    }
    if replicates == 0 {
        bail!("--replicates must be at least 1");
    }
    let (track, seed) = load_track(stream_path)?;
    let mut rows = Vec::new();
    let mut retrieval = None;
    for replicate in 0..replicates {
        // A fresh system, and for the Achiral arms a fresh organisation.
        let mut system = build(arm, replicate)?;
        let results = replay_stream(&track.stream, system.as_mut(), top_k);
        if replicate == 0 {
            retrieval = system.retrieval_echo();
        }
        rows.push(rows_of(&track.stream, &track.spec, &results));
    }
    Ok(ProceduralRun {
        schema: SCHEMA.to_string(),
        label,
        arm: arm.to_string(),
        seed,
        stream_file: stream_path
            .file_name()
            .map_or_else(String::new, |n| n.to_string_lossy().into_owned()),
        stream_sha256: sha256_file(&stream_path.to_string_lossy())?,
        top_k,
        replicates,
        cognoscenti_commit: current_commit(),
        retrieval,
        rows,
    })
}

/// One line per arm and replicate 0: what the run found, before any report.
pub fn summary_line(run: &ProceduralRun) -> String {
    let count = |cat: &str| {
        let rows: Vec<_> = run.rows[0].iter().filter(|r| r.category == cat).collect();
        format!("{}/{}", rows.iter().filter(|r| r.hit).count(), rows.len())
    };
    format!(
        "{} seed {} replicate 0: adherence {}, near-miss firing {}, superseded-rule {}, scope leaks {}",
        run.arm,
        run.seed,
        count("follow"),
        count("near"),
        count("sup"),
        count("leak")
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::baselines::Bm25System;
    use crate::procedural_report::analyse;

    fn dir(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("cogn-proc-cli-{name}-{}", std::process::id()));
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn generate_writes_the_stream_the_replay_will_accept_and_the_same_seed_gives_the_same_bytes() {
        let d = dir("gen");
        let (a, b) = (d.join("a.jsonl"), d.join("b.jsonl"));
        let sha_a = generate(4242, &a).unwrap();
        let sha_b = generate(4242, &b).unwrap();
        assert_eq!(sha_a, sha_b);
        assert_ne!(sha_a, generate(4243, &d.join("c.jsonl")).unwrap());
        let (track, seed) = load_track(&a).unwrap();
        assert_eq!(seed, 4242);
        assert_eq!(track.stream.questions().count(), 108);
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn a_stream_that_was_edited_or_has_no_seed_header_is_refused() {
        let d = dir("edit");
        let p = d.join("s.jsonl");
        generate(17, &p).unwrap();
        let text = std::fs::read_to_string(&p).unwrap();
        std::fs::write(&p, text.replacen("billing", "invoicing", 1)).unwrap();
        assert!(load_track(&p).is_err());
        std::fs::write(&p, text.replace("# procedural-seed=17\n", "")).unwrap();
        assert!(load_track(&p).is_err());
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn a_replay_records_every_replicate_and_question_and_names_its_stream() {
        let d = dir("replay");
        let p = d.join("s.jsonl");
        let sha = generate(17, &p).unwrap();
        let run = replay_with(&p, "bm25", 2, 1, Some("tuning".into()), |_, _| {
            Ok(Box::new(Bm25System::new()))
        })
        .unwrap();
        assert_eq!(run.rows.len(), 2);
        assert_eq!(run.rows[0].len(), 108);
        assert_eq!(
            (run.arm.as_str(), run.seed, run.stream_sha256.as_str()),
            ("bm25", 17, sha.as_str())
        );
        // bm25 is deterministic: the replicates agree row for row.
        assert_eq!(run.rows[0], run.rows[1]);
        assert!(summary_line(&run).starts_with("bm25 seed 17 replicate 0: adherence "));
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn an_unknown_arm_or_zero_replicates_stops_before_any_request() {
        let d = dir("bad");
        let p = d.join("s.jsonl");
        generate(17, &p).unwrap();
        assert!(replay(&p, "magic", 1, 1, None).is_err());
        assert!(replay(&p, "bm25", 0, 1, None).is_err());
        std::fs::remove_dir_all(&d).unwrap();
    }

    #[test]
    fn replay_save_load_and_report_round_trip_through_files() {
        let d = dir("e2e");
        let mut paths = Vec::new();
        for (arm, seed) in [
            ("declarative", 4242),
            ("procedural", 4242),
            ("declarative", 4243),
            ("procedural", 4243),
        ] {
            let s = d.join(format!("{seed}.jsonl"));
            generate(seed, &s).unwrap();
            // Both arms stand in with bm25 here; the Achiral arms need a server.
            let mut run = replay_with(&s, "bm25", 2, 1, None, |_, _| {
                Ok(Box::new(Bm25System::new()))
            })
            .unwrap();
            run.arm = arm.to_string();
            let out = d.join(format!("{arm}-{seed}.json"));
            run.save(&out).unwrap();
            paths.push(out);
        }
        let runs: Vec<_> = paths
            .iter()
            .map(|p| ProceduralRun::load(p).unwrap())
            .collect();
        let a = analyse(&runs).unwrap();
        // Identical systems: no difference, so no claim.
        assert!(!a.verdict.unwrap().claim);
        let args = ProceduralArgs::parse_from([
            "procedural",
            "report",
            "--results",
            paths[0].to_str().unwrap(),
            paths[1].to_str().unwrap(),
            paths[2].to_str().unwrap(),
            paths[3].to_str().unwrap(),
        ]);
        run(&args).unwrap();
        assert!(d.join("report").join("index.html").exists());
        std::fs::remove_dir_all(&d).unwrap();
    }
}
